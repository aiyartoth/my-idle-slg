import { describe, expect, it } from 'vitest'
import { findCardByName } from './cardCatalog'

describe('按名字找卡', () => {
  it('名字完全一致才找得到，空名字找不到', () => {
    expect(findCardByName(' 火枪手 ')?.name).toBe('火枪手')
    expect(findCardByName('黄巾步兵')?.id).toBe('yellow-infantry')
    expect(findCardByName('圣殿骑士')).toMatchObject({ rarity: 'purple', atk: 2, hp: 7, move: 2, speed: 2, range: 1 })
    expect(findCardByName('天公将军张角')).toMatchObject({ rarity: 'orange', profession: '法师', cd: 5, atk: 2, hp: 7, move: 2, speed: 2, range: 3 })
    expect(findCardByName('大法师')).toMatchObject({ rarity: 'purple', race: 'human', profession: '法师' })
    expect(findCardByName('水元素')).toMatchObject({ id: 'water-elemental', rarity: 'white', atk: 2, hp: 4, profession: '元素' })
    expect(findCardByName('山丘之王')).toMatchObject({ rarity: 'orange', race: 'dwarf', profession: '战士' })
    expect(findCardByName('战士')).toMatchObject({ id: 'warrior', rarity: 'blue', atk: 3, hp: 6 })
    expect(findCardByName('死亡骑士')).toMatchObject({ id: 'death-knight', rarity: 'orange', profession: '死亡骑士' })
    expect(findCardByName('先知萨尔')).toMatchObject({ id: 'thrall', rarity: 'orange', race: 'orc', profession: '萨满' })
    expect(findCardByName('灰烬使者莫格莱尼')).toMatchObject({ rarity: 'orange', atk: 3, hp: 8 })
    expect(findCardByName('女妖之王希尔瓦娜斯')?.race).toBe('undead')
    expect(findCardByName('幽灵狼')).toMatchObject({ id: 'ghost-wolf', rarity: 'white', atk: 2, hp: 3 })
    expect(findCardByName('兽人步兵')).toMatchObject({ id: 'grunt', rarity: 'green', race: 'orc', atk: 3, hp: 6 })
    expect(findCardByName('地狱火')).toMatchObject({ id: 'infernal', rarity: 'purple', atk: 4, hp: 8 })
    expect(findCardByName('凤凰')).toMatchObject({ id: 'phoenix', rarity: 'purple', atk: 3, hp: 6 })
    expect(findCardByName('米莎')).toMatchObject({ id: 'misha', rarity: 'blue', atk: 2, hp: 6 })
    expect(findCardByName('科多兽')).toMatchObject({ id: 'kodo', rarity: 'blue', race: 'orc' })
    expect(findCardByName('冰霜巨龙')).toMatchObject({ id: 'frost-wyrm', rarity: 'purple', race: 'undead' })
    expect(findCardByName('骷髅')).toMatchObject({ id: 'skeleton', rarity: 'white', atk: 1, hp: 2 })
    expect(findCardByName('飞行器')?.race).toBe('gnome')
    expect(findCardByName('女巫')?.race).toBe('highElf')
    expect(findCardByName('')).toBeUndefined()
    expect(findCardByName('没有这张')).toBeUndefined()
  })
})
