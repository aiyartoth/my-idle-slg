import { describe, expect, it } from 'vitest'
import { ALL_CARDS } from './cardCatalog'
import { cardTypeLine, isLegendCard, isMageType } from './cardType'

describe('卡面类型行', () => {
  it('按万智牌的类别和子类来写', () => {
    const line = (name: string) => cardTypeLine(ALL_CARDS.find((card) => card.name === name)!)
    expect(line('步兵')).toBe('生物-人类/步兵')
    expect(line('牧师')).toBe('生物-人类/法师/牧师')
    expect(line('女巫')).toBe('生物-高等精灵/法师/女巫')
    expect(line('破法者')).toBe('生物-高等精灵/破法者')
    expect(line('大法师瓦格斯')).toBe('传奇生物-人类/法师')
    expect(isLegendCard(ALL_CARDS.find((card) => card.name === '大法师瓦格斯')!)).toBe(true)
    expect(isLegendCard(ALL_CARDS.find((card) => card.name === '步兵')!)).toBe(false)
    expect(line('飞行器')).toBe('机械-侏儒/飞行器/载具')
    expect(line('攻城器械')).toBe('机械-矮人/攻城/载具')
    expect(line('水元素')).toBe('元素')
    expect(line('山丘之王穆拉丁')).toBe('传奇生物-矮人/战士')
    expect(line('迫击炮小队')).toBe('生物-矮人/炮兵')
    expect(line('狮鹫骑士')).toBe('生物-矮人/狮鹫')
    expect(line('战士')).toBe('生物-人类/战士')
    expect(line('圣骑士加文拉德')).toBe('传奇生物-人类/圣骑士')
    expect(line('暗影牧师')).toBe('生物-人类/法师/牧师')
    expect(line('术士')).toBe('生物-人类/法师/术士')
    expect(line('死亡骑士达里安')).toBe('传奇生物-人类/死亡骑士')
    expect(line('先知萨尔')).toBe('传奇生物-兽人/萨满')
    expect(line('背叛者伊利丹')).toBe('传奇生物-暗夜精灵/恶魔猎手')
    expect(line('太阳之王凯尔萨斯')).toBe('传奇生物-血精灵/法师')
    expect(line('凤凰')).toBe('元素')
    expect(line('凤凰蛋')).toBe('元素')
    expect(line('米莎')).toBe('生物-野兽')
    expect(line('兽人步兵')).toBe('生物-兽人/步兵')
    expect(line('女猎手')).toBe('生物-暗夜精灵/女猎手')
    expect(line('冰霜巨龙')).toBe('生物-亡灵/冰霜巨龙')
    expect(line('山岭巨人')).toBe('生物-暗夜精灵/巨人')
    expect(line('骷髅')).toBe('生物-亡灵/骷髅')
    expect(line('侏儒技师')).toBe('生物-侏儒/技师')
    expect(line('工匠大师格尔宾')).toBe('传奇生物-侏儒/技师')
    expect(isLegendCard(ALL_CARDS.find((card) => card.name === '工匠大师格尔宾')!)).toBe(true)
    expect(line('地狱犬')).toBe('生物-恶魔/地狱犬')
    expect(line('末日守卫')).toBe('生物-恶魔/末日守卫')
    expect(line('龙鹰')).toBe('生物-血精灵/龙鹰')
    expect(line('血骑士')).toBe('生物-血精灵/圣骑士')
    expect(line('高等精灵弓手')).toBe('生物-高等精灵/弓手')
    expect(line('游侠温蕾萨')).toBe('传奇生物-高等精灵/猎人')
    expect(line('矮人猎手')).toBe('生物-矮人/猎人')
    expect(line('奇美拉')).toBe('生物-野兽/奇美拉')
    expect(line('侏儒修理兵')).toBe('生物-侏儒/修理兵')
    expect(line('法师米尔豪斯')).toBe('传奇生物-侏儒/法师')
    expect(isLegendCard(ALL_CARDS.find((card) => card.name === '法师米尔豪斯')!)).toBe(true)
    expect(line('恶魔卫士')).toBe('生物-恶魔/卫士')
    expect(line('魅魔')).toBe('生物-恶魔/魅魔')
    expect(line('魔导师')).toBe('生物-血精灵/法师')
    expect(line('远行者')).toBe('生物-血精灵/弓手')
    expect(line('高等精灵剑士')).toBe('生物-高等精灵/剑士')
    expect(line('角鹰兽')).toBe('生物-野兽/角鹰兽')
    expect(line('火元素')).toBe('元素')
    expect(line('树妖')).toBe('生物-暗夜精灵/树妖')
  })

  it('图鉴里每张牌都有类型行', () => {
    expect(ALL_CARDS.every((card) => cardTypeLine(card).length > 0)).toBe(true)
  })

  it('牧师和女巫算法师，破法者不算', () => {
    const card = (name: string) => ALL_CARDS.find((item) => item.name === name)!
    expect(isMageType(card('牧师'))).toBe(true)
    expect(isMageType(card('女巫'))).toBe(true)
    expect(isMageType(card('法师'))).toBe(true)
    expect(isMageType(card('破法者'))).toBe(false)
    expect(isMageType(card('巫医'))).toBe(false)
    expect(isMageType(card('亡灵巫师'))).toBe(false)
    expect(isMageType(card('水元素'))).toBe(false)
    expect(isMageType(card('冰霜法师'))).toBe(true)
    expect(isMageType(card('术士'))).toBe(true)
    expect(isMageType(card('暗影牧师'))).toBe(true)
    expect(isMageType(card('萨满德雷克塔尔'))).toBe(false)
    expect(isMageType(card('死亡骑士达里安'))).toBe(false)
    expect(isMageType(card('大法师吉安娜'))).toBe(true)
    expect(isMageType(card('污染者古尔丹'))).toBe(true)
    expect(isMageType(card('月神祭司泰兰德'))).toBe(true)
    expect(isMageType(card('先知萨尔'))).toBe(false)
    expect(isMageType(card('工匠大师格尔宾'))).toBe(false)
    expect(isMageType(card('血骑士'))).toBe(false)
    expect(isMageType(card('游侠温蕾萨'))).toBe(false)
    expect(isMageType(card('法师米尔豪斯'))).toBe(true)
    expect(isMageType(card('魔导师'))).toBe(true)
    expect(isMageType(card('魅魔'))).toBe(false)
    expect(isMageType(card('火元素'))).toBe(false)
  })
})
